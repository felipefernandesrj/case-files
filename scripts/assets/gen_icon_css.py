#!/usr/bin/env python3
"""Generate public/css/pixel-icons.css from public/assets/manifest.json.

Each `<svg class="icon"><use href="#i-x">` keeps its SVG (accessibility, forced colours,
test/icons.mjs) but shows the keyed pixel-art PNG on top when one is in the manifest.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
m = json.loads((ROOT / "public/assets/manifest.json").read_text())
ids = sorted(i["id"] for i in m["items"] if i.get("kind") == "icon")
out = ["/* generated by scripts/assets/gen_icon_css.py from assets/manifest.json; do not edit */",
       "@media not (forced-colors: active) {"]
for i in ids:
    out.append(f'  svg.icon:has(> use[href="#{i}"]) {{ background: url(/assets/icons/{i}-64.png) center / contain no-repeat; image-rendering: pixelated; }}')
    out.append(f'  svg.icon:has(> use[href="#{i}"]) > use {{ display: none; }}')
out.append("}")
(ROOT / "public/css/pixel-icons.css").write_text("\n".join(out) + "\n")
print(len(ids), "icons")
